"""Sanity checks of the instance data (Data/Data1.xlsx, Data/Data2.xlsx).

  python Phase1_rerun/data_check.py            # writes Phase1_rerun/results/data_check.txt

Part 1 compares the expected daily workload of each resource with its capacity
(offered load = arrivals x probability x mean service time).
Part 2 shows what per-patient physician time would make the thesis staffing levels feasible.
Part 3 evaluates the physician-only benchmark plans with the corrected model, to show how
the triage bottleneck drives that objective.
"""
import io
import os
import sys
from contextlib import redirect_stdout

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402
import hgasa  # noqa: E402

TESTS = ["lab_test", "ultrasonic", "xray", "ct"]
P_TEST = np.array([0.92, 0.22, 0.29, 0.55])
P_EXAM = 0.6


def conditional_test_probabilities():
    """Tests are redrawn until at least one is selected: P(test | at least one)."""
    p_none = np.prod(1 - P_TEST)
    return P_TEST / (1 - p_none), p_none


def main():
    buf = io.StringIO()
    with redirect_stdout(buf):
        p_cond, p_none = conditional_test_probabilities()
        print("DATA CHECK  (generated by Phase1_rerun/data_check.py)\n")
        print(f"Test routing: P(no test drawn) = {p_none:.4f}; conditional probabilities after redraw = "
              + ", ".join(f"{t} {p:.3f}" for t, p in zip(TESTS, p_cond)))

        for name in ("medium", "large"):
            inst = common.load_instance(name)
            st = inst.service_times
            raw = pd.read_excel(os.path.join(common.DATA, common.INSTANCE_FILES[name]), sheet_name="Sheet1",
                                header=None)
            side = {str(k).strip(): v for k, v in zip(raw.iloc[1:8, 10], raw.iloc[1:8, 11])}
            print(f"\n=== {name.upper()} instance ({common.INSTANCE_FILES[name]}) ===")
            print("Service-time sheet (min): triage {0}, consult {1}, lab {2}, US {3}, X-ray {4}, CT {5}, revisit {6}, "
                  "result delays lab/US/X-ray/CT {7}/{8}/{9}/{10}".format(*st))
            print("Side table in 'Sheet1' (min):", side)
            print("  -> test totals = processing + result delay: lab {:.2f}, US {:.2f}, X-ray {:.2f}, CT {:.2f}"
                  .format(st[2] + st[7], st[3] + st[8], st[4] + st[9], st[5] + st[10]))
            print(f"Rooms R = {inst.num_consultant_rooms}; triage nurses (physician-only model) = "
                  f"{inst.num_triage_nurses}; units per diagnostic modality = {inst.num_lab_tests}")
            print("\nDay        arrivals  physician-h  nurse-h  triage-h  peak arrivals/h  peak physicians needed")
            for d in range(7):
                rates = np.array(inst.arrival_rates[d])
                n = rates.sum()
                phys_min = st[1] + P_EXAM * st[6]
                nurse_min = st[0] + phys_min
                peak = rates.max()
                print(f"{common.DAY_NAMES[d]:10s} {n:8.1f} {n * phys_min / 60:12.1f} {n * nurse_min / 60:8.1f} "
                      f"{n * st[0] / 60:9.1f} {peak:16.1f} {peak * phys_min / 60:23.1f}")
            n = sum(inst.arrival_rates[0])
            print("Diagnostic load on Monday (h/day per unit): " + ", ".join(
                f"{t} {n * P_EXAM * p * st[2 + i] / 60 / inst.num_lab_tests:.1f}" for i, (t, p) in enumerate(zip(TESTS, p_cond))))
            phys_min = st[1] + P_EXAM * st[6]
            print(f"Per patient: physician {phys_min:.1f} min, nurse {st[0] + phys_min:.1f} min "
                  f"(triage {st[0]} + consultations {phys_min:.1f})")
            print(f"Triage utilization in the physician-only model: {n * st[0] / 60 / (24 * inst.num_triage_nurses):.0%}")

        print("\n=== Staffing reported in the thesis vs workload (Monday) ===")
        cases = [("medium", "thesis best, nurse+physician", [4, 4, 2], [0, 1, 0, 0, 0, 0], 3),
                 ("large", "thesis best, nurse+physician", [7, 7, 4], [0, 0, 0, 0, 0, 0, 0, 1, 0], 3)]
        for name, label, ft, pt, lp in cases:
            inst = common.load_instance(name)
            st = inst.service_times
            hours = 8 * sum(ft) + lp * sum(pt)
            n = sum(inst.arrival_rates[0])
            need = n * (st[1] + P_EXAM * st[6]) / 60
            print(f"{name}: {label}: {hours} physician-h staffed vs {need:.1f} h of physician work "
                  f"-> utilization {need / hours:.0%}; per-patient physician time that would give 85% "
                  f"utilization: {0.85 * hours * 60 / n:.1f} min (data: {st[1] + P_EXAM * st[6]:.1f} min)")
        print("AP-ESB&B objective reported for the physician-only medium instance: 86.65 (thesis Table 5.10).")
        print("If the objective counts physician-hours, physician staffing <= 86.65 h/day, i.e. below the "
              f"{sum(common.load_instance('medium').arrival_rates[0]) * 18 / 60:.0f} h of work implied by the data.")

        print("\n=== Physician-only model (corrected), Monday medium, 300 replications ===")
        inst = common.load_instance("medium")
        for phys in ([3, 4, 2, 0, 1, 0, 0, 0, 0], [4, 4, 3, 0, 1, 0, 0, 0, 0], [5, 5, 3, 0, 0, 0, 0, 0, 0]):
            ev = hgasa.Evaluator("physician_only", inst, 0, 300, 4242)
            r = ev.reevaluate(np.array(phys), 300, 4242)
            print(f"physicians {phys}: Z = {r['objective']:.2f} +/- {r['objective_hw']:.2f} "
                  f"(staffing {r['staffing_cost']:.1f}, waiting {r['waiting']:.2f} h, delay {r['delay']:.2f} h)")
        print("Waiting in this model excludes the triage queue, which has a single nurse at >100% utilization;")
        print("triage therefore meters the flow to the physicians (at most 12 patients/h).")

    text = buf.getvalue()
    print(text)
    out = os.path.join(common.HERE, "results", "data_check.txt")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write(text)
    print("written", out)


if __name__ == "__main__":
    main()
